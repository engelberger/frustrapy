def test_baseline_fixtures_present_and_intact():
    """Every fixture named in the manifest exists with the recorded row count and
    sha256 (the baseline has not drifted or been partially committed)."""
    for name, info in {**MANIFEST["tables"], **MANIFEST["scans"]}.items():
        path = os.path.join(BASELINE, name)
        assert os.path.exists(path), f"missing baseline fixture: {name}"
        assert _sha256(path) == info["sha256"], f"baseline fixture changed: {name}"
        n = info.get("n_rows", info.get("n_variants"))
        with open(path) as fh:
            rows = sum(1 for _ in fh) - 1
        assert rows == n, f"{name}: {rows} rows, manifest says {n}"


def test_panel_covers_single_and_multi_chain():
    """The panel spans a single-chain and a genuine multi-chain structure, all
    three modes, and a multi-chain scan with a target in a non-default chain."""
    for base in ("1crn", "1zni"):
        for mode in MODES:
            assert f"{base}.pdb_{mode}" in MANIFEST["tables"]
    # 1zni configurational has cross-chain contacts (ChainRes1 != ChainRes2).
    rows = _rows(os.path.join(BASELINE, "1zni.pdb_configurational"))
    cross = sum(1 for r in rows if r[2] != r[3])
    assert cross > 0, "multi-chain fixture has no cross-chain contacts"
    # A scan target lives in chain B (not the first chain).
    assert any(c == "B" for _, c in _scan_targets("1zni"))


