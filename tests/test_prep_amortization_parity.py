"""Golden regression baseline for the prep-amortization work.

This freezes the current (pre-optimization) FrustraPy outputs so the prep
amortization (computing the per-structure data prep once and reusing it across a
saturation scan's N x 20 variants) can be proven to change no numbers. It loads
the committed fixtures under ``tests/data/prep_baseline/`` and asserts the current
code reproduces them. It must PASS now (proving the baseline is faithful) and stay
passing through the amortization work.

Panel: a single-chain structure (1crn) and a genuine multi-chain structure (1zni,
insulin, 4 chains with cross-chain contacts), all three modes, plus a small
saturation scan (single- and multi-chain). The stored tables are the ``lammps``
oracle; the native backend is checked against them.

The fixtures and this test are regenerated by
``tests/data/prep_baseline/generate_baseline.py``. See
``docs/PREP_AMORTIZATION_PLAN.md`` for the design.

NOTE on PATH: the engine spawns a bare ``python3`` subprocess, so run ``pytest``
from an activated venv (see conftest.py).
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import warnings

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
BASELINE = os.path.join(DATA, "prep_baseline")

with open(os.path.join(BASELINE, "manifest.json")) as _fh:
    MANIFEST = json.load(_fh)

SEQ_DIST = MANIFEST["seq_dist"]
STRUCT_PDB = {"1crn": os.path.join(DATA, "1crn.pdb"), "1zni": os.path.join(DATA, "1zni.pdb")}
MODES = ("configurational", "mutational", "singleresidue")

try:
    import frustrapy_native  # noqa: F401

    HAS_NATIVE = True
except ImportError:
    HAS_NATIVE = False

# Column layout (0-based) of the parsed FrustrationData tables.
#   contact (config/mut), 14 cols: Res1 Res2 ChainRes1 ChainRes2 DensityRes1
#     DensityRes2 AA1 AA2 NativeEnergy DecoyEnergy SDEnergy FrstIndex Welltype
#     FrstState
#   singleresidue, 8 cols: Res ChainRes DensityRes AA NativeEnergy DecoyEnergy
#     SDEnergy FrstIndex
_NUM_COLS = {
    "configurational": [4, 5, 8, 9, 10, 11],
    "mutational": [4, 5, 8, 9, 10, 11],
    "singleresidue": [2, 4, 5, 6, 7],
}
# Identity / class columns that must match exactly (residue, chain, amino acid,
# well type, and the frustration class) -- string equality, not numeric tolerance.
_ID_COLS = {
    "configurational": [0, 1, 2, 3, 6, 7, 12, 13],
    "mutational": [0, 1, 2, 3, 6, 7, 12, 13],
    "singleresidue": [0, 1, 3],
}
_FRST_COL = {"configurational": 11, "mutational": 11, "singleresidue": 7}

# CPU parity tolerance for the native backend vs the lammps oracle (the table
# prints to 3 decimals; allow a single last-digit rounding step).
_NATIVE_TOL = 1.5e-3


